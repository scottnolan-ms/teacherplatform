const {advanceBatches, markedStudents} = await load('./model.ts');
const complete = {id: 1, label: 'Batch 1', group: 'Group 1', date: '2026-11-16', stage: 'Results ready', progress: 0, sheets: demoSheets().slice(0, 4)};
const processing = {id: 2, label: 'Batch 2', group: 'Group 2', date: '2026-11-17', stage: 'Marking', progress: 99, sheets: demoSheets().slice(0, 2)};
const newUpload = {id: 3, label: 'Batch 3', group: 'Whole class', date: '2026-11-18', stage: 'Uploading', progress: 0, sheets: demoSheets()};
let concurrent = advanceBatches([complete, processing, newUpload], true);
assert.equal(concurrent[0], complete, 'Earlier results are untouched by later uploads');
assert.equal(concurrent[1].progress, 100, 'Marking continues while another batch uploads');
assert.equal(concurrent[2].progress, 8, 'The new upload has independent progress');
concurrent = advanceBatches(concurrent, true);
assert.equal(concurrent[1].stage, 'Results ready');
assert.equal(concurrent[2].stage, 'Uploading', 'Finishing marking must not finish the new batch');
assert.deepEqual(markedStudents(concurrent), ['Emma Johnson', 'Liam Martinez', 'Sophia Okonkwo', 'Noah Okafor'], 'Marking counts deduplicate students across batches');
const reviewing = advanceBatches([{...newUpload, stage: 'Matching', progress: 100}], false);
assert.equal(reviewing[0].stage, 'Review matches', 'Uncertain matches still block automatic marking');
const automatic = advanceBatches([{...processing, stage: 'Matching', progress: 100}], false);
assert.equal(automatic[0].stage, 'Transcribing', 'A clean batch may skip optional review');
assert.equal(advanceBatches([complete], true)[0], complete);
console.log('Concurrent paper+ batches preserve results, progress independently and enforce per-batch review.');

