const {studentPages,replaceStudentPage}=await load('./model.ts');
const classBatch={...complete,sheets:[{...demoSheets()[0],id:201},{...demoSheets()[1],id:202}]};
const extraBatch={...complete,id:2,sheets:[{...demoSheets()[0],id:203,file:'Emma extra.jpg'},{...demoSheets()[0],id:204,excluded:true}]};
assert.deepEqual(studentPages([classBatch,extraBatch],'Emma Johnson').map(sheet=>sheet.id),[201,203],'Original pages include only this student across all batches, excluding discarded pages');
const replacement={...newUpload,id:3,sheets:[{id:205,file:'Clearer Emma.jpg',student:'Emma Johnson',method:'Assigned by you'}]};
const replaced=replaceStudentPage([classBatch,extraBatch],'Emma Johnson',201,replacement);
assert.deepEqual(studentPages(replaced,'Emma Johnson').map(sheet=>sheet.id),[203,205],'A replacement replaces one page, keeping the student’s other pages');
assert.deepEqual(studentPages(replaced,'Liam Martinez').map(sheet=>sheet.id),[202],'Classmates retain their pages');
assert.ok(markedStudents(replaced).includes('Liam Martinez'),'Classmates retain their marked results while the replacement uploads');
assert.equal(replaced[1],extraBatch,'Other batches remain untouched');
assert.deepEqual(replaceStudentPage([classBatch],'Emma Johnson',202,replacement),[classBatch],'Cannot replace another student’s page');
assert.deepEqual(replaceStudentPage([classBatch],'Emma Johnson',201,{...replacement,sheets:[]}),[classBatch],'An empty upload cannot remove the original page');
console.log('Student-scoped original pages and replacement isolation passed.');
const {applyStudentCapture}=await load('./model.ts');
for(const origin of ['file upload','webcam','phone']){
 const captured={...replacement,id:300,sheets:[{id:301,file:origin,student:'Wrong auto-match',method:origin}]};
 const added=applyStudentCapture([classBatch],{kind:'add',student:'Emma Johnson'},captured);
 assert.equal(studentPages(added,'Emma Johnson').length,2,`${origin} adds pages only for the selected student`);
 assert.equal(studentPages(added,'Wrong auto-match').length,0);
 assert.equal(studentPages(added,'Liam Martinez').length,1);
 const revised=applyStudentCapture([classBatch],{kind:'replace',student:'Emma Johnson',pageId:201},captured);
 assert.deepEqual(studentPages(revised,'Emma Johnson').map(page=>page.file),[origin],`${origin} replaces one page instead of appending`);
 assert.ok(markedStudents(revised).includes('Liam Martinez'));
 assert.equal(classBatch.sheets[0].file,'7A-scans.pdf · page 1','The original data is not mutated');
 assert.equal(applyStudentCapture([classBatch],{kind:'replace',student:'Emma Johnson',pageId:201},{...captured,sheets:[...captured.sheets,{...captured.sheets[0],id:302}]}).length,1,'Multiple captures cannot accidentally replace one page');
}
console.log('Shared files, webcam and phone capture intentions stay scoped and distinguish add from replace.');
