import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
const code=ts.transpileModule(fs.readFileSync(new URL('./report-data.ts',import.meta.url),'utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {tierMatches,matchesProgress,resultDistribution}=await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
assert.deepEqual([24,25,50,75,76,null].filter(n=>tierMatches(n,'25–75%')),[25,50,75]);
assert.equal(tierMatches(null,'0–100%'),false);
assert.equal(tierMatches(null,'Awaiting marking'),true);
assert.equal(tierMatches(null,'Not started'),true);
assert.equal(tierMatches(49,'Below 50%'),true);
assert.equal(tierMatches(50,'Below 50%'),false);
assert.equal(tierMatches(100,'100%'),true);
assert.equal(tierMatches(99,'100%'),false);
assert.deepEqual([0,24,25,75,76,100].filter(n=>matchesProgress(n,{condition:'Between',amount:25,maximum:75})),[25,75]);
assert.equal(matchesProgress(25,{condition:'Less than',amount:25}),false);
assert.equal(matchesProgress(25,{condition:'At most',amount:25}),true);
assert.equal(matchesProgress(0,null),true);
const bins=resultDistribution([0,3,4,99,100,null]);
assert.equal(bins.length,25);assert.equal(bins[0],2);assert.equal(bins[1],1);assert.equal(bins[24],2);assert.equal(bins.reduce((a,b)=>a+b,0),5);
assert.equal(resultDistribution([null,null]).every(n=>n===0),true);
console.log('Result ranges, pending bands, progress boundaries and histogram totals passed.');
